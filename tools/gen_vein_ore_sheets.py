"""Issue #654 (the maintainer's decision of 2026-10-30): the map vein ores show GT's ore texture in the material's colour
on the base game's ore lumps.

GT draws an ore block as stone with the material's `ore` texture of its icon set tinted in its colour and the
`ore_OVERLAY` on top (gregtech/textures/blocks/materialicons/<set>/). For each icon set of the vein ores this writes an
effect sheet graphics/entity/fork/gt-ore-<set>.png in the layout of the base game's stone sheet (8 stages x 8
variations, here 64 pixels a cell at scale 1): each lump of the stone sheet (its alpha only) filled with the set's ore
texture, tiled at GT's 16 pixels a block, its overlay baked in, in grey; prototypes/165-fork-ore-veins.lua draws it
over the untinted stone lumps as the resource's `stages_effect`, tinted in the material's colour.
prototypes/data/vein-ore-sets.lua lists each vein ore's icon set (GT's material of the ore mix, tools/gen_ore_mixes.py).

    python tools/gen_vein_ore_sheets.py --gt C:/00_Repositories/GT5-Unofficial --factorio "D:/Program Files/SteamLibrary/steamapps/common/Factorio"
"""
import argparse
import re
from pathlib import Path

from PIL import Image

import gen_gt_icons

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "graphics" / "entity" / "fork"
LUA = ROOT / "prototypes" / "data" / "vein-ore-sets.lua"
CELL, FRAMES, VARIATIONS = 128, 8, 8
OUT_CELL = 64


def ore_sets(gt):
    """Gregtorio vein ore -> GT icon set, from prototypes/data/ore-mixes.lua's mixes (the four ores and GT's names)"""
    mats = gen_gt_icons.gt_materials(gt)
    text = (ROOT / "prototypes" / "data" / "ore-mixes.lua").read_text(encoding="utf-8")
    out = {}
    for m in re.finditer(r'primary = "([^"]+)", secondary = "([^"]+)", between = "([^"]+)", sporadic = "([^"]+)", '
                         r'gt = \{ "([^"]+)", "([^"]+)", "([^"]+)", "([^"]+)" \}', text):
        for ore, name in zip(m.groups()[:4], m.groups()[4:]):
            iset = mats.get(name, ("DULL", None))[0]
            if iset.startswith("CUSTOM/") or iset == "NONE":
                iset = "DULL"
            out.setdefault(ore, iset)
    return out


def texture(gt, iset, name):
    p = gt / "src/main/resources/assets/gregtech/textures/blocks/materialicons" / iset / f"{name}.png"
    if not p.exists():
        p = gt / "src/main/resources/assets/gregtech/textures/blocks/materialicons/DULL" / f"{name}.png"
    if not p.exists():
        return None
    img = Image.open(p).convert("RGBA")
    return img.crop((0, 0, img.width, img.width))       # (an animated texture: its first frame)


def sheet(stone, gt, iset):
    """the effect sheet of an icon set"""
    ore, overlay = texture(gt, iset, "ore"), texture(gt, iset, "ore_OVERLAY")
    scale = CELL // 2 // ore.width          # GT's block (16 pixels) on a tile (64 pixels of the 128 cell at scale 0.5)
    pat = ore.resize((ore.width * scale, ore.height * scale), Image.NEAREST)
    if overlay:
        pat.alpha_composite(overlay.resize(pat.size, Image.NEAREST))
    grey = Image.new("RGBA", stone.size, (0, 0, 0, 0))
    for y in range(0, stone.height, pat.height):
        for x in range(0, stone.width, pat.width):
            grey.paste(pat, (x, y))
    px, sp = grey.load(), stone.load()
    for y in range(stone.height):
        for x in range(stone.width):
            r, g, b, a = px[x, y]
            lum = int(0.3 * r + 0.59 * g + 0.11 * b)
            px[x, y] = (lum, lum, lum, a * sp[x, y][3] // 255)
    return grey.resize((OUT_CELL * FRAMES, OUT_CELL * VARIATIONS), Image.LANCZOS)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--gt", type=Path, required=True)
    ap.add_argument("--factorio", type=Path, required=True, help="the Factorio installation (data/base/graphics)")
    a = ap.parse_args()
    stone = Image.open(a.factorio / "data/base/graphics/entity/stone/stone.png").convert("RGBA")
    sets = ore_sets(a.gt)
    # (icon sets with the same ore texture share one sheet, named after the first)
    file_of, seen = {}, {}
    for iset in sorted(set(sets.values())):
        img = sheet(stone, a.gt, iset)
        key = img.tobytes()
        if key not in seen:
            seen[key] = iset.lower()
            target = OUT / f"gt-ore-{iset.lower()}.png"
            if not (target.exists() and Image.open(target).convert("RGBA").tobytes() == key):
                img.save(target, optimize=True)
        file_of[iset] = seen[key]
    for old in OUT.glob("gt-ore-*.png"):
        if old.stem[len("gt-ore-"):] not in seen.values():
            old.unlink()
    sets = {o: file_of[s] for o, s in sets.items()}
    lua = ["--- Generated by tools/gen_vein_ore_sheets.py (issue #654): each map vein ore's GT icon set, whose sheet",
           "--- graphics/entity/fork/gt-ore-<set>.png (sets with the same ore texture share the first's sheet)",
           "--- prototypes/165-fork-ore-veins.lua draws; do not edit, run it again.",
           "return {"]
    lua += [f'\t["{o}"] = "{s}",' for o, s in sorted(sets.items())]
    lua.append("}")
    LUA.write_bytes(("\n".join(lua) + "\n").encode("utf-8"))
    print(f"{len(sets)} ores, {len(set(sets.values()))} sheets")


if __name__ == "__main__":
    main()
