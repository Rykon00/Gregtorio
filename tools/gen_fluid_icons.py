"""Issue #654 (the maintainer's decision of 2026-10-30): GT's own fluid textures for Gregtorio's fluids.

Every shown fluid of a devcheck check log (section FLUIDS) whose icon is not yet its own file is matched with the fluid
textures of the GT5-Unofficial checkout (GT's `gregtech/textures/blocks/fluids/fluid.<name>`, GT++'s `miscutils`,
GoodGenerator's `<camelCase>.still`): by name, with the molten and plasma prefixes, and ALIASES. A match writes
graphics/fluids/<fluid>.png through tools/gen_gt_icons.py --fluid (the texture's still frame, GT's colours) and lists the
fluid in prototypes/data/fluid-icons.lua, which prototypes/196-fork-subgroups.lua applies. tools/fluid-textures.tsv
records every fluid's texture; the fluids without one keep their colour icon, for the reason in REASONS (written there
too).

    python tools/devcheck/devcheck.py check
    python tools/gen_fluid_icons.py --gt C:/00_Repositories/GT5-Unofficial [--log .devcheck/last-run.log]
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TSV = ROOT / "tools" / "fluid-textures.tsv"
LUA = ROOT / "prototypes" / "data" / "fluid-icons.lua"

#: Gregtorio fluid -> GT texture spec, where the names differ
ALIASES = {
    "excited-dimensionally-transcendent-crude-catalyst": "fluid.exciteddtcc",
    "excited-dimensionally-transcendent-prosaic-catalyst": "fluid.exciteddtpc",
    "excited-dimensionally-transcendent-resplendent-catalyst": "fluid.exciteddtrc",
    "excited-dimensionally-transcendent-exotic-catalyst": "fluid.exciteddtec",
    "excited-dimensionally-transcendent-stellar-catalyst": "fluid.exciteddtsc",
    "sulfuric-light-fuel": "fluid.liquid_sufluriclight_fuel",          # (GT's file name has the typo)
    "helium-plasma": "fluid.heliumplasma", "nitrogen-plasma": "fluid.nitrogenplasma",
    "combustion-promoter": "gt:goodgenerator/textures/blocks/fluids/combustionPromotor.still",
    "tachyon-rich-temporal-fluid": "fluid.temporalfluid", "spatially-enlarged-fluid": "fluid.spatialfluid",
    "molten-fluxed-electrum": "fluid.molten.fluxed", "molten-vibrant-alloy": "fluid.molten.vibrant",
    "molten-energetic-alloy": "fluid.molten.energetic", "molten-crystalline-alloy": "fluid.molten.crystalline",
    "molten-melodic-alloy": "fluid.molten.melodic", "molten-stellar-alloy": "fluid.molten.stellar",
}
#: fluids whose GT texture is not used, with the reason
SKIP = {n: "GT's oil textures are plain black in every frame; the base game's icons tell the oils apart (issue #318, "
           "FORK_FLUID_ICONS_KEPT)" for n in ("heavy-oil", "light-oil", "medium-oil", "crude-oil")}
#: why the other fluids keep a colour icon (the group, by the first match)
REASONS = [
    (r"^molten-", "GT draws the melts it has no texture for with molten.autogenerated in the material's colour; the "
                  "colour icons (and tools/gen_gt_icons.py --molten) are that"),
    (r"-plasma$", "GT draws the plasmas with plasma.autogenerated in the material's colour; the colour icons are that"),
    (r".", "GT has no texture of its own for this fluid: it draws it with fluid.autogenerated (a gas or liquid in the "
           "material's colour), which Gregtorio's colour icons stand for"),
]


def nh(s):
    return re.sub(r"[^a-z0-9]", "", s.lower())


def textures(gt):
    """{(kind, key): spec}: kind "", "molten" or "plasma"; the spec as tools/gen_gt_icons.py --fluid takes it"""
    a = gt / "src/main/resources/assets"
    out = {}

    def put(kind, key, spec):
        out.setdefault((kind, nh(key)), spec)
    for p in sorted((a / "gregtech/textures/blocks/fluids").glob("*.png")):
        st = p.stem
        if "autogenerated" in st or st.startswith("fluid.potion") or st.endswith(".flow"):
            continue
        s = re.sub(r"^(liquid_|gas_)", "", re.sub(r"\.still$", "", re.sub(r"^fluid\.(fluid\.)?", "", st)))
        m = re.match(r"^(molten|plasma)\.(.+)$", s)
        put(m.group(1) if m else "", m.group(2) if m else s, st)
    for p in sorted((a / "miscutils/textures/blocks/fluids").glob("*.png")):
        st = p.stem
        if "autogenerated" in st:
            continue
        s = re.sub(r"^fluid\.", "", st)
        m = re.match(r"^(molten|plasma)\.(.+)$", s)
        put(m.group(1) if m else "", m.group(2) if m else s, f"gt:miscutils/textures/blocks/fluids/{st}")
    for p in sorted((a / "goodgenerator/textures/blocks/fluids").glob("*.still.png")):
        put("", p.stem[:-len(".still")], f"gt:goodgenerator/textures/blocks/fluids/{p.stem}")
    return out


def match(name, tex):
    if name in ALIASES:
        return ALIASES[name]
    kind, base = "", name
    if name.startswith("molten-"):
        kind, base = "molten", name[len("molten-"):]
    elif name.endswith("-plasma"):
        kind, base = "plasma", name[:-len("-plasma")]
    spec = tex.get((kind, nh(base)))
    if not spec and kind == "molten":
        spec = tex.get(("", nh(base)))     # (GT's element fluids are its melts: fluid.lithium, fluid.silicon, ...)
    return spec


def fluids(log):
    """the shown fluids of the check log with their icon file"""
    text = Path(log).read_text(encoding="utf-8", errors="replace")
    m = re.search(r"DEVCHECK-FLUIDS-BEGIN\n(.*?)DEVCHECK-FLUIDS-END", text, re.S)
    if not m:
        sys.exit("no section FLUIDS in " + str(log) + " (run `devcheck.py check` first)")
    out = {}
    for line in m.group(1).splitlines():
        r = line.split("\t")
        if len(r) >= 8 and r[4] == "false":
            out[r[0]] = r[7]
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--gt", type=Path, required=True, help="GT5-Unofficial checkout")
    ap.add_argument("--log", type=Path, default=ROOT / ".devcheck" / "last-run.log")
    a = ap.parse_args()
    tex = textures(a.gt)
    have = {}
    if LUA.exists():
        have = dict(re.findall(r'^\t\["([^"]+)"\] = "([^"]+)",', LUA.read_text(encoding="utf-8"), re.M))
    rows, todo = [], []
    for name, icon in sorted(fluids(a.log).items()):
        own = icon.endswith(f"/graphics/fluids/{name}.png")
        spec = match(name, tex)
        if name in SKIP:
            rows.append((name, "", SKIP[name]))
        elif spec and (not own or name in have):
            todo.append((name, spec))
            rows.append((name, spec, ""))
        elif own:
            rows.append((name, "", "its own icon"))
        else:
            rows.append((name, "", next(why for rx, why in REASONS if re.search(rx, name))))
    if todo:
        subprocess.run([sys.executable, str(ROOT / "tools" / "gen_gt_icons.py"), "--gt", str(a.gt), "--fluid",
                        *[f"{n}={s}" for n, s in todo]], check=True, stdout=subprocess.DEVNULL)
    lua = ["--- Generated by tools/gen_fluid_icons.py (issue #654): the fluids with GT's own texture as their icon",
           "--- (graphics/fluids/<fluid>.png from tools/gen_gt_icons.py --fluid), applied by prototypes/196-fork-subgroups.lua;",
           "--- do not edit, run it again. The value is GT's texture.", "return {"]
    lua += [f'\t["{n}"] = "{s}",' for n, s in todo]
    lua.append("}")
    LUA.write_bytes(("\n".join(lua) + "\n").encode("utf-8"))
    out = ["# Issue #654: each shown fluid's GT texture (tools/gen_fluid_icons.py), or why it keeps its icon",
           "# fluid\tGT texture\treason"]
    out += [f"{n}\t{s}\t{w}" for n, s, w in rows]
    TSV.write_bytes(("\n".join(out) + "\n").encode("utf-8"))
    print(f"{len(todo)} fluids with GT's texture, {sum(1 for r in rows if r[2] == 'its own icon')} with their own icon, "
          f"{sum(1 for r in rows if r[2] and r[2] != 'its own icon')} keep a colour icon (reasons in {TSV.name})")


if __name__ == "__main__":
    main()
